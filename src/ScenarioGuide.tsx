export function ScenarioGuide({step, onStep, onClose}: {step: number; onStep: (step: number) => void; onClose: () => void}) {
  const navigate = useNavigate();
  const location = useLocation();
  const campaigns = useStore(s => s.campaigns);
  const [campaignId, setCampaignId] = useState('CP-104');
  const [collapsed, setCollapsed] = useState(false);
  const [side, setSide] = useState<'left' | 'right'>('right');
  const body = useRef<HTMLDivElement>(null);
  // Follow a campaign or copy the user opens while walking through the guide.
  useEffect(() => {
    const id = location.pathname.match(/^\/(?:campaigns|coupons)\/([^/]+)/)?.[1];
    if (id && campaigns.some(c => c.id === id)) setCampaignId(id);
  }, [location.pathname, campaigns]);
  useEffect(() => { body.current?.scrollTo({top: 0}); }, [step]);
  const steps = scenarioSteps(campaignId);
  const current = steps[step];
  function go(next: number) {
    onStep(next);
    navigate(steps[next].path);
  }
  return <aside className={`tour tour-${side} ${collapsed ? 'tour-collapsed' : ''}`} aria-label="Пошаговый сценарий работы со Срезом">
    <header className="tour-header">
      <div><small>СЦЕНАРИЙ · ШАГ {step + 1} ИЗ {steps.length}</small><span>{current.section}</span></div>
      <div className="tour-tools">
        <button className="tour-move" title="Переместить подсказку" aria-label="Переместить подсказку" onClick={() => setSide(side === 'right' ? 'left' : 'right')}><MoveHorizontal size={17}/></button>
        <button title={collapsed ? 'Развернуть инструкцию' : 'Свернуть инструкцию'} aria-label={collapsed ? 'Развернуть инструкцию' : 'Свернуть инструкцию'} aria-expanded={!collapsed} aria-controls="scenario-instructions" onClick={() => setCollapsed(!collapsed)}>{collapsed ? <ChevronUp size={18}/> : <ChevronDown size={18}/>}</button>
        <button title="Закрыть сценарий" aria-label="Закрыть сценарий" onClick={onClose}><X size={18}/></button>
      </div>
    </header>
    <div className="tour-progress" role="progressbar" aria-label="Текущий шаг сценария" aria-valuemin={1} aria-valuemax={steps.length} aria-valuenow={step + 1}><span style={{width: `${(step + 1) / steps.length * 100}%`}}/></div>
    <div id="scenario-instructions" hidden={collapsed}>
      <div className="tour-body" ref={body}>
        <label className="tour-step-picker">Перейти к шагу<select value={step} onChange={e => go(Number(e.target.value))}>{steps.map((item, i) => <option key={i} value={i}>{i + 1}. {item.title}</option>)}</select></label>
        <h2>{current.title}</h2>
        <p className="tour-goal">{current.goal}</p>
        <h3>Что сделать</h3>
        <ol className="tour-actions">{current.actions.map(action => <li key={action}>{action}</li>)}</ol>
        <div className="tour-result"><Check size={18}/><div><h3>Что должно получиться</h3><p>{current.expected}</p></div></div>
        {current.tip && <p className="tour-tip">{current.tip}</p>}
        <button className="text-button tour-open" onClick={() => navigate(current.path)}>Открыть раздел этого шага<ArrowRight size={14}/></button>
      </div>
      <footer className="tour-footer"><Button disabled={step === 0} onClick={() => go(step - 1)}><ArrowLeft size={15}/>Назад</Button><Button primary onClick={() => step === steps.length - 1 ? onClose() : go(step + 1)}>{step === steps.length - 1 ? 'Завершить сценарий' : 'Следующий шаг'}{step !== steps.length - 1 && <ArrowRight size={15}/>}</Button></footer>
    </div>
  </aside>;
}
